"""Django settings for Codemm.

Secrets and database credentials come from environment variables, loaded from
a local .env file (see .env.example). Nothing secret is committed.
"""

import os
from pathlib import Path

from django.core.exceptions import ImproperlyConfigured
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent.parent

load_dotenv(BASE_DIR / ".env")


def env(name, default=None):
    value = os.environ.get(name, default)
    if value is None or value == "":
        raise ImproperlyConfigured(f"Set {name} in your .env file (see .env.example).")
    return value


SECRET_KEY = env("DJANGO_SECRET_KEY")
